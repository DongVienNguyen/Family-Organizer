import { describe, it, expect, vi } from 'vitest';
import { createAccountWorkspace } from './accountWorkspace.js';
import { WalletApiError } from './api.js';
const result = (permission = 'manage', revision = 1): any => ({ account: { id: 'a', name: 'Synthetic', type: 'cash', currency: 'VND', ownerUserId: 'adult', accessMode: 'shared', openingMinor: '9007199254740993', openingDate: '2026-10-17', revision, archivedAt: null, permission }, metadata: { accountId: 'a', createdAt: null, updatedAt: null, createdBy: null, updatedBy: null, excludedFromStats: false, creditLimitMinor: null, dueDay: null, balanceDisplay: 'book' } });
function fixture() {
    const saved = result(), api: any = { status: vi.fn().mockResolvedValue({ active: true, storageVersion: 4 }), accounts: vi.fn().mockResolvedValue([saved.account]), account: vi.fn().mockResolvedValue(saved), balance: vi.fn().mockResolvedValue({ date: '2026-10-17', book: { minor: '9007199254740993', currency: 'VND' }, cleared: { minor: '0', currency: 'VND' } }), createAccount: vi.fn().mockResolvedValue(saved), updateAccount: vi.fn().mockResolvedValue(saved), archiveAccount: vi.fn().mockResolvedValue(saved) };
    const workspace = createAccountWorkspace(api, { date: () => '2026-10-17', newRequestId: () => 'owned' });
    return { api, workspace };
}
describe('session-owned Wallet account workspace', () => {
    it('keeps Wallet inactive without listing or exposing money', async () => { const { api, workspace: w } = fixture(); api.status.mockResolvedValue({ active: false, storageVersion: 4 }); await w.refresh(); expect(w.snapshot()).toMatchObject({ phase: 'inactive', accounts: [], selected: null }); expect(api.accounts).not.toHaveBeenCalled(); });
    it('shows exact balances, guards read-only accounts, and prevents create while a draft is open', async () => {
        const { api, workspace: w } = fixture();
        await w.refresh();
        await w.select('a');
        expect(w.snapshot().balance?.book.minor).toBe('9007199254740993');
        w.edit('en-US');
        const draft = w.snapshot().form;
        w.openCreate('vi-VN');
        expect(w.snapshot().form).toBe(draft);
        w.cancel();
        api.account.mockResolvedValue(result('read'));
        await w.refresh();
        w.edit('en-US');
        await w.archive('a', 1);
        expect(w.snapshot().form).toBeNull();
        expect(api.archiveAccount).not.toHaveBeenCalled();
    });
    it('retains invalid draft and only resets it after a confirmed successful save', async () => {
        const { api, workspace: w } = fixture();
        await w.refresh();
        w.openCreate('vi-VN');
        w.change({ opening: 'bad' });
        await w.save();
        expect(w.snapshot().form).toMatchObject({ invalid: true, draft: { opening: 'bad' } });
        expect(api.createAccount).not.toHaveBeenCalled();
        w.change({ name: 'Synthetic', opening: '9.007.199.254.740.993' });
        await w.save();
        expect(api.createAccount).toHaveBeenCalledWith(expect.objectContaining({ openingMinor: '9007199254740993' }), 'owned');
        expect(w.snapshot()).toMatchObject({ form: null, command: { phase: 'success' } });
    });
    it('keeps an unknown intent across view subscriptions and only retries the original body/key', async () => {
        const { api, workspace: w } = fixture();
        api.createAccount.mockRejectedValueOnce(new WalletApiError(0, 'network', 'NETWORK_ERROR', 'owned', true));
        await w.refresh();
        w.openCreate('en-US');
        w.change({ name: 'Synthetic', opening: '123' });
        await w.save();
        const stop = w.subscribe(() => { });
        stop();
        w.change({ opening: '999' });
        w.cancel();
        w.openCreate('en-US');
        expect(w.snapshot().form?.draft.opening).toBe('123');
        await w.save();
        expect(api.createAccount).toHaveBeenCalledTimes(1);
        await w.retry();
        expect(api.createAccount.mock.calls[1]).toEqual(api.createAccount.mock.calls[0]);
        expect(w.snapshot().form).toBeNull();
    });
    it('clears all public financial data synchronously while verifying permission and removes a revoked draft', async () => {
        const { api, workspace: w } = fixture();
        await w.refresh();
        await w.select('a');
        w.edit('en-US');
        let release!: (value: unknown) => void;
        api.accounts.mockImplementationOnce(() => new Promise(r => release = r));
        const loading = w.refresh();
        expect(w.snapshot()).toMatchObject({ phase: 'checking', accounts: [], selected: null, balance: null, form: null });
        await Promise.resolve();
        release([]);
        await loading;
        expect(w.snapshot()).toMatchObject({ phase: 'ready', accounts: [], form: null });
    });
    it('ignores a stale list after a newer refresh revoked access', async () => {
        const { api, workspace: w } = fixture();
        let release!: (value: unknown) => void;
        api.accounts.mockImplementationOnce(() => new Promise(r => release = r));
        const old = w.refresh();
        await Promise.resolve();
        api.accounts.mockResolvedValue([]);
        await w.refresh();
        release([result().account]);
        await old;
        expect(w.snapshot().accounts).toEqual([]);
    });
    it('does not overwrite a conflict or issue a second command without explicit reload', async () => {
        const { api, workspace: w } = fixture();
        await w.refresh();
        await w.select('a');
        w.edit('en-US');
        w.change({ name: 'Draft' });
        api.updateAccount.mockRejectedValue(new WalletApiError(409, 'conflict', 'CONFLICT', 'owned'));
        await w.save();
        expect(w.snapshot()).toMatchObject({ form: { draft: { name: 'Draft' } }, command: { phase: 'conflict' } });
        w.change({ name: 'overwrite' });
        await w.save();
        expect(api.updateAccount).toHaveBeenCalledTimes(1);
        api.account.mockResolvedValue(result('manage', 2));
        await w.reload();
        expect(w.snapshot().form).toMatchObject({ draft: { name: 'Synthetic' }, initial: { account: { revision: 2 } } });
    });
    it('preserves the draft input locale across refresh rather than reinterpreting its separators', async () => {
        const { workspace: w } = fixture();
        await w.refresh();
        w.openCreate('vi-VN');
        w.change({ name: 'Synthetic', opening: '1.234' });
        await w.refresh();
        expect(w.snapshot().form).toMatchObject({ locale: 'vi-VN', draft: { opening: '1.234' } });
    });
    it('does not turn a successful write into a rejected command when readback fails', async () => {
        const { api, workspace: w } = fixture();
        await w.refresh();
        w.openCreate('en-US');
        w.change({ name: 'Synthetic' });
        api.accounts.mockRejectedValue(new WalletApiError(503, 'offline', 'UNAVAILABLE', undefined));
        await w.save();
        expect(w.snapshot()).toMatchObject({ phase: 'error', form: null, command: { phase: 'success' } });
        expect(api.createAccount).toHaveBeenCalledTimes(1);
    });
    it('disposal purges drafts and ignores late read responses', async () => {
        const { api, workspace: w } = fixture();
        let release!: (value: unknown) => void;
        api.status.mockImplementationOnce(() => new Promise(r => release = r));
        const pending = w.refresh();
        w.dispose();
        release({ active: true });
        await pending;
        expect(w.snapshot()).toMatchObject({ phase: 'disposed', accounts: [], selected: null, form: null });
        expect(api.accounts).not.toHaveBeenCalled();
    });
    it('does not expose a cached monetary command receipt through an invalidated view', async () => {
        const { workspace: w } = fixture();
        await w.refresh();
        w.openCreate('en-US');
        w.change({ name: 'Synthetic' });
        await w.save();
        expect(w.snapshot().command).not.toHaveProperty('result');
        const refresh = w.refresh();
        expect(JSON.stringify(w.snapshot())).not.toContain('9007199254740993');
        await refresh;
    });
    it('binds archive confirmation to the same selected account revision', async () => {
        const { api, workspace: w } = fixture();
        await w.refresh();
        await w.select('a');
        api.account.mockResolvedValue(result('manage', 2));
        await w.refresh();
        await w.archive('a', 1);
        expect(api.archiveAccount).not.toHaveBeenCalled();
        await w.archive('a', 2);
        expect(api.archiveAccount).toHaveBeenCalledWith('a', 2, 'owned');
    });
    it('keeps a hidden unknown draft across refresh until the user explicitly resumes it', async () => {
        const { api, workspace: w } = fixture();
        api.createAccount.mockRejectedValue(new WalletApiError(0, 'network', 'NETWORK_ERROR', 'owned', true));
        await w.refresh();
        w.openCreate('en-US');
        w.change({ name: 'Synthetic retained', opening: '123' });
        await w.save();
        w.hideForm();
        await w.refresh();
        expect(w.snapshot().form).toBeNull();
        expect(w.snapshot().command.phase).toBe('unknown');
        w.resumeForm();
        expect(w.snapshot().form?.draft).toMatchObject({ name: 'Synthetic retained', opening: '123' });
        expect(api.createAccount).toHaveBeenCalledTimes(1);
    });
    it('restores only the currently selected archived account at its confirmed revision', async () => {
        const { api, workspace: w } = fixture();
        await w.refresh();
        await w.select('a');
        await w.restore('a', 1);
        expect(api.updateAccount).not.toHaveBeenCalled();
        api.account.mockResolvedValue({ ...result(), account: { ...result().account, archivedAt: '2026-10-17T00:00:00.000Z' } });
        await w.refresh();
        await w.restore('a', 2);
        expect(api.updateAccount).not.toHaveBeenCalled();
        await w.restore('a', 1);
        expect(api.updateAccount).toHaveBeenCalledWith('a', 1, { archived: false }, 'owned');
    });
});
